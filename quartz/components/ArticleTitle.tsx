import { QuartzComponent, QuartzComponentConstructor, QuartzComponentProps } from "./types"
import { classNames } from "../util/lang"

const ArticleTitle: QuartzComponent = ({ fileData, displayClass }: QuartzComponentProps) => {
  // The homepage already starts with its authored Hebrew H1. Avoid rendering
  // Quartz's filename fallback (`index`) as a duplicate technical heading.
  if (fileData.slug === "index") return null

  const title = (fileData.frontmatter?.name_he as string | undefined) ?? fileData.frontmatter?.title
  if (title) {
    return <h1 class={classNames(displayClass, "article-title")}>{title}</h1>
  } else {
    return null
  }
}

ArticleTitle.css = `
.article-title {
  margin: 2rem 0 0 0;
}
`

export default (() => ArticleTitle) satisfies QuartzComponentConstructor
